"""`control-plane-api serve-grants`: the separate minimal ASGI app for run-grant verifiers (architecture.md §2.7;
C-RUNNER 3.0.0). Serves only:

* `GET /.well-known/jwks.json` - the public keys of the run-grant key class. `REPLICANT_RUN_GRANT_JWKS_SOURCE=file` reads
  the JWK Set at `REPLICANT_RUN_GRANT_JWKS_FILE` (generated by `replicant dev up` from the signing key; public half only).
  Private key members (`d`, `p`, `q`, `dp`, `dq`, `qi`, `k`) are stripped defensively.
* `GET /grants/revoked` - job_ids whose status became cancelled/failed/taken_over and run_ids cancelled or terminal
  with SecurityViolation, derived from `jobs_read` (C-STATE rule 5), merged with the exec revocation feed polled from
  runner-api/runner-local `GET /v1/revocations` every 10 s; ETag + `Cache-Control: max-age=30`; entries dropped 24 h
  after the last possible grant exp.
* `GET /healthz`, `GET /readyz`.
"""
from __future__ import annotations

import asyncio
import contextlib
import datetime as dt
import hashlib
import json
import logging
from typing import Any

import httpx
from fastapi import FastAPI, Request, Response
from fastapi.responses import JSONResponse
from sqlalchemy import text

from control_plane_api.config import Settings, read_secret
from control_plane_api.db import OPERATOR_SCOPE, Database

log = logging.getLogger(__name__)

PRIVATE_MEMBERS = {"d", "p", "q", "dp", "dq", "qi", "k", "oth"}
RETENTION = dt.timedelta(hours=24) + dt.timedelta(hours=24)   # last grant exp (≤ job lifetime window) + 24 h; M1 bound
RUN_ID_RE_PREFIX = "run_"


def load_jwks(settings: Settings) -> dict[str, Any]:
    if settings.run_grant_jwks_source != "file":
        raise SystemExit("REPLICANT_RUN_GRANT_JWKS_SOURCE=kms is not implemented in M1 (local profile uses file)")
    if not settings.run_grant_jwks_file:
        raise SystemExit("REPLICANT_RUN_GRANT_JWKS_FILE is required")
    with open(settings.run_grant_jwks_file, encoding="utf-8") as f:
        raw = json.load(f)
    keys = raw.get("keys") if isinstance(raw, dict) and "keys" in raw else [raw]
    pub = [{k: v for k, v in key.items() if k not in PRIVATE_MEMBERS} for key in keys]
    return {"keys": pub}


class RevocationState:
    def __init__(self) -> None:
        self.exec_runs: dict[str, str] = {}      # run_id -> revoked_at (exec feed)
        self.cursor: dict[str, str] = {}
        self.cache: tuple[float, bytes, str] | None = None


def create_grants_app(settings: Settings, db: Database | None = None) -> FastAPI:
    jwks = load_jwks(settings)
    jwks_body = json.dumps(jwks, sort_keys=True).encode()
    db = db or Database(settings)
    state = RevocationState()

    @contextlib.asynccontextmanager
    async def lifespan(app: FastAPI):  # noqa: ANN202
        task = None
        if settings.exec_revocations_urls and settings.background_tasks:
            task = asyncio.create_task(_poll_exec_feed(settings, state))
        yield
        if task:
            task.cancel()
        await db.dispose()

    app = FastAPI(title="run-grants", lifespan=lifespan, docs_url=None, redoc_url=None, openapi_url=None)

    @app.get("/.well-known/jwks.json")
    async def jwks_route() -> Response:
        return Response(jwks_body, media_type="application/json", headers={"Cache-Control": "max-age=300"})

    @app.get("/grants/revoked")
    async def revoked(request: Request) -> Response:
        now = asyncio.get_running_loop().time()
        if state.cache is None or now - state.cache[0] > 5:
            body = await _revocation_list(db, state)
            etag = '"' + hashlib.sha256(body).hexdigest()[:32] + '"'
            state.cache = (now, body, etag)
        _, body, etag = state.cache
        if request.headers.get("if-none-match") == etag:
            return Response(status_code=304, headers={"ETag": etag, "Cache-Control": "max-age=30"})
        return Response(body, media_type="application/json", headers={"ETag": etag, "Cache-Control": "max-age=30"})

    @app.get("/healthz")
    async def healthz() -> dict[str, str]:
        return {"status": "ok"}

    @app.get("/readyz")
    async def readyz() -> JSONResponse:
        ok = await db.ping()
        return JSONResponse({"status": "ok" if ok else "degraded", "db": ok}, status_code=200 if ok else 503)

    return app


async def _revocation_list(db: Database, state: RevocationState) -> bytes:
    cutoff = dt.datetime.now(dt.UTC) - RETENTION
    jobs: list[dict[str, str]] = []
    runs: dict[str, str] = {}
    try:
        async with db.tx(scope=OPERATOR_SCOPE) as conn:
            for r in (await conn.execute(text(
                    "SELECT job_id, coalesce(terminal_at, updated_at) AS at FROM jobs_read.jobs WHERE status IN "
                    "('cancelled', 'failed', 'taken_over') AND coalesce(terminal_at, updated_at) > :c ORDER BY job_id"),
                    {"c": cutoff})).all():
                jobs.append({"id": r.job_id, "revoked_at": r.at.isoformat().replace("+00:00", "Z")})
            if await db.has_relation("jobs_read.job_runs"):
                for r in (await conn.execute(text(
                        "SELECT run_id, coalesce(finished_at, started_at, now()) AS at FROM jobs_read.job_runs WHERE "
                        "(phase = 'Cancelled' OR (phase = 'Failed' AND reason = 'SecurityViolation')) AND "
                        "coalesce(finished_at, started_at, now()) > :c"), {"c": cutoff})).all():
                    runs[r.run_id] = r.at.isoformat().replace("+00:00", "Z")
    except Exception as e:  # noqa: BLE001 - projection unavailable: still serve the exec feed (fail open is wrong
        # for a deny list, so callers keep their last good copy; we answer 200 with what we know and log)
        log.warning("revocation list from jobs_read failed: %s", type(e).__name__)
    for rid, at in state.exec_runs.items():
        runs.setdefault(rid, at)
    body = {"generated_at": dt.datetime.now(dt.UTC).isoformat().replace("+00:00", "Z"), "job_ids": jobs,
            "run_ids": [{"id": k, "revoked_at": v} for k, v in sorted(runs.items())]}
    return json.dumps(body, sort_keys=True).encode()


async def _poll_exec_feed(settings: Settings, state: RevocationState) -> None:
    token = read_secret(settings.exec_revocations_token_file)
    headers = {"Authorization": f"Bearer {token}"} if token else {}
    async with httpx.AsyncClient(timeout=5) as c:
        while True:
            for url in settings.exec_revocations_urls:
                try:
                    params = {"since": state.cursor[url]} if url in state.cursor else {}
                    r = await c.get(url, headers=headers, params=params)
                    if r.status_code == 200:
                        data = r.json()   # C-RUNNER RevocationList {revoked: [{run_id, job_id, at, reason}], next_cursor}
                        for it in data.get("revoked") or []:
                            rid = it.get("run_id")
                            if isinstance(rid, str) and rid.startswith(RUN_ID_RE_PREFIX):
                                state.exec_runs.setdefault(rid, it.get("at") or dt.datetime.now(dt.UTC).isoformat())
                        if data.get("next_cursor"):
                            state.cursor[url] = data["next_cursor"]
                        state.cache = None
                except Exception as e:  # noqa: BLE001 - the feed is best-effort; the projection path still works
                    log.debug("exec revocation feed %s: %s", url, type(e).__name__)
            await asyncio.sleep(settings.exec_revocations_poll_seconds)

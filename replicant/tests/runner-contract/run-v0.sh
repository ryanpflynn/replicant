#!/bin/sh
# Runner contract cases (test-strategy.md §5.3) and SEC-EGRESS-01..08 (§8.1) against runner-local IN THE LIVE v0
# STACK (replicant dev up --profile v0 [--with-observability]): the real sandbox network replicant-sbx (sbx-dns,
# sbx-edge, egress proxy, mirrors), run-grants, Gitea, the broker, repo-mirror and the gateway shim (script backend).
# The driver is go/cmd/runner-local/smoke in SMOKE_TARGET=v0 mode, run in a `plat-` container on replicant-core.
#
#   tests/runner-contract/run-v0.sh [driver args]      e.g. --mode contract | --only SEC-EGRESS,RC-RUN-13
# Results: tests/runner-contract/results-v0.json (git-ignored). Exit status = the driver's.
set -eu
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
S="$ROOT/dev/.secrets/secrets"
NET=replicant-core
for c in runner-local gateway-shim repo-mirror sbx-edge sbx-dns egress-proxy; do
  podman ps --format '{{.Names}}' | grep -qx "replicant_${c}_1" || { echo "v0 service $c is not running (replicant dev up --profile v0)"; exit 2; }
done
ip() { podman inspect "replicant_$1_1" --format "{{(index .NetworkSettings.Networks \"$NET\").IPAddress}}"; }
CORE="runner-local=$(ip runner-local):8480 postgres-replicant=$(ip postgres-replicant):5432 temporal=$(ip temporal):7233"
CORE="$CORE github-token-broker=$(ip github-token-broker):8080 control-plane-api=$(ip control-plane-api):8401"

# Render the egress probe scenario (runner-contract-egress/egress_probe) with the core targets for SEC-EGRESS-03.
SET="$ROOT/tests/fixtures/gateway-scripts/runner-contract-egress"
mkdir -p "$SET"
cp "$ROOT/tests/fixtures/gateway-scripts/walkthrough-ledger-api/implementer.agent_report.json" "$SET/"
B64="$(sed "s#@CORE_TARGETS@#$CORE#" "$ROOT/tests/security/egress/egress-probe.sh" | base64 | tr -d '\n')"
cat > "$SET/egress_probe.yaml" <<YAML
# GENERATED by tests/runner-contract/run-v0.sh (do not edit): SEC-EGRESS probe inside the sandbox, then the canned
# walkthrough fix so the implementer run completes normally (diff + handoff + StructuredOutput).
schema: replicant.gateway-script/v1
name: runner-contract-egress-probe
protocol: anthropic_messages
finish: "Done."
turns:
  - respond:
      text: "Probing sandbox egress."
      tool_use: {name: Bash, input: {command: "echo $B64 | base64 -d > /tmp/egress-probe.sh && bash /tmp/egress-probe.sh > /replicant/out/handoff.md 2>&1; sleep 20; cat /replicant/out/handoff.md", description: "Egress probe", timeout: 600000}}
      usage: {input_tokens: 2000, output_tokens: 40}
  - respond:
      tool_use: {name: Read, input: {file_path: "\${cwd}/internal/ledger/ledger.go"}}
      usage: {input_tokens: 9000, output_tokens: 60}
  - respond:
      tool_use:
        name: Edit
        input:
          file_path: "\${cwd}/internal/ledger/ledger.go"
          old_string: "\t\tfxReversal := c.FXFeeMinor\n"
          new_string: "\t\tfxReversal := Prorate(c.FXFeeMinor, refundMinor, c.AmountMinor)\n"
      usage: {input_tokens: 11000, output_tokens: 120}
  - respond:
      structured_output_from: implementer.agent_report.json
      usage: {input_tokens: 12000, output_tokens: 200}
YAML

RES="$ROOT/tests/runner-contract/results-v0.json"
podman rm -f plat-contract-driver >/dev/null 2>&1 || true
SOCK="${REPLICANT_CONTAINER_SOCKET:-$(podman info --format '{{.Host.RemoteSocket.Path}}' | sed 's#^unix://##')}"
# The engine socket lets the driver inject faults (stop Temporal, kill a sandbox container, pause agentd).
podman run --name plat-contract-driver --network "$NET" -v "$ROOT:/src:ro" --security-opt label=disable \
  -v "$SOCK:/var/run/docker.sock" -e CONTAINER_HOST=unix:///var/run/docker.sock -v plat-gomod:/go/pkg/mod -v plat-gocache:/root/.cache \
  -v replicant_runner-local-state:/runner-state:ro -v "$S:/secrets:ro" \
  -e SMOKE_TARGET=v0 -e GOWORK=off -e GOFLAGS=-mod=mod \
  -e S3_ENDPOINT=http://s3.replicant.localhost:8333 -e S3_ACCESS_KEY=replicant-services -e "S3_SECRET_KEY=$(cat "$S/s3_services_secret")" \
  -e RUNNER_URL=http://runner-local:8480 -e RUNNER_SANDBOX_URL=http://runner-local:8490 -e SHIM_URL=http://gateway-shim:8420 \
  -e WORKER_TOKEN_FILE=/secrets/runner_worker_token -e READER_TOKEN_FILE=/secrets/runner_revocations_token \
  -e SHIM_TOKEN_FILE=/secrets/gateway_service_token -e GRANT_KEY_FILE=/secrets/run_grant_signing_key \
  -e TEMPORAL_ADDRESS=temporal:7233 -e RUNNER_STATE_DIR=/runner-state \
  -e GITEA_URL=http://gitea:3300 -e GITEA_ADMIN_PASSWORD_FILE=/secrets/gitea_admin_password -e RESULTS_FILE=/tmp/results.json \
  -w /src/go/cmd/runner-local docker.io/library/golang:1.26 \
  sh -c "go build -o /tmp/smoke ./smoke && exec /tmp/smoke $*"
RC=$(podman inspect plat-contract-driver --format '{{.State.ExitCode}}')
podman cp plat-contract-driver:/tmp/results.json "$RES" >/dev/null 2>&1 || true
podman rm -f plat-contract-driver >/dev/null 2>&1 || true
echo "driver exit $RC (results: $RES)"
exit "$RC"

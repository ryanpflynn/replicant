"""Emit, for each GraphDefinition, (1) an explicit LangGraph StateGraph module and (2) a Mermaid
diagram drawn by LangGraph from the compiled graph. Then prove the module builds a graph identical to
PregelEngine's compile of the same YAML.

The generated modules are documentation of what the engine executes ("the compiled form"); the
workflow never imports them. Usage:
    python tools/graph_codegen.py ../graphs/definitions ../graphs/generated
"""

from __future__ import annotations

import importlib.util
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

import yaml  # noqa: E402

from replicant_orchestration import nodes  # noqa: E402,F401
from replicant_orchestration.engines.pregel import _name, _sink_name, build_state_graph  # noqa: E402
from replicant_orchestration.graphspec import TERMINAL_PREFIX, parse_definition  # noqa: E402

HEADER = '''"""GENERATED by tools/graph_codegen.py from graphs/definitions/{file}. Do not edit.

graph/{name} (workflowType {wtype}). This is the LangGraph StateGraph that PregelEngine compiles for
this definition when no codebase-binding modifiers apply. Every node is a workflow-side node that runs
its NodeType through NodeContext (all I/O in explicit-ID activities); conditional edges evaluate FGL
guards against JobState through host.route(). Compile with checkpointer=InMemorySaver().
"""

from __future__ import annotations

from typing import Any

from langgraph.graph import END, START, StateGraph

from replicant_orchestration.engines.pregel import ReplicantGraphState, node, router, sink, start_router


def build(host: Any) -> StateGraph:
    g = StateGraph(ReplicantGraphState)
'''


class _Host:
    """Inert host: building and drawing a graph never runs node code."""

    def route(self, key: str) -> list[str]:  # pragma: no cover
        raise RuntimeError("not executed")


def gen_module(path: pathlib.Path) -> tuple[str, object]:
    doc = yaml.safe_load(path.read_text())
    spec = parse_definition(doc, version=1, digest="sha256:" + "0" * 64)
    out = [HEADER.format(file=path.name, name=doc["metadata"]["name"], wtype=spec.workflow_type)]
    out.append("    # nodes (node key -> NodeCatalog type, phase)")
    for k, n in spec.nodes.items():
        extra = f", maxVisits {n.max_visits}" if n.max_visits else ""
        out.append(f'    g.add_node("{k}", node(host, "{k}"))  # {n.type}, phase {n.phase}{extra}')
    terminals = sorted({t for e in spec.edges for t in e.targets if t.startswith(TERMINAL_PREFIX)})
    out.append("    # terminal sinks end:<outcome> (graphs/README.md section 6)")
    for t in terminals:
        out.append(f'    g.add_node("{_sink_name(t)}", sink("{t[len(TERMINAL_PREFIX):]}"))')
        out.append(f'    g.add_edge("{_sink_name(t)}", END)')
    out.append("    # resume-at-node after Continue-As-New (ADR-01-004)")
    out.append(f"    g.add_conditional_edges(START, start_router, {list(spec.nodes)!r})")
    out.append("    # edges")
    for e in spec.edges:
        if len(e.source) > 1:
            out.append(f"    g.add_edge({list(e.source)!r}, {_name(e.to)!r})  # join: wait for all branches")
        elif e.switch:
            for b in e.switch:
                out.append(f"    #   {e.source[0]} -> {_name(b.to)} when {b.when}")
            out.append(f"    #   {e.source[0]} -> {_name(e.default)} otherwise")
            out.append(f"    g.add_conditional_edges({e.source[0]!r}, router(host, {e.source[0]!r}), "
                       f"{sorted({_name(t) for t in e.targets})!r})")
        else:
            out.append(f"    g.add_edge({e.source[0]!r}, {_name(e.to)!r})")
    if spec.boundaries:
        out.append("    # Continue-As-New boundaries (enforced by the host before the node runs): "
                   + ", ".join(f"{b.kind} before {b.before}" for b in spec.boundaries))
    out.append("    return g\n")
    return "\n".join(out) + "\n", spec


def topology(g) -> tuple[set, set]:
    cg = g.compile().get_graph()
    return set(cg.nodes), {(e.source, e.target, e.conditional) for e in cg.edges}


def main(src: str, dst: str) -> int:
    src_p, dst_p = pathlib.Path(src), pathlib.Path(dst)
    dst_p.mkdir(parents=True, exist_ok=True)
    bad = 0
    for path in sorted(src_p.glob("*.yaml")):
        code, spec = gen_module(path)
        mod_path = dst_p / f"{path.stem.replace('-', '_')}_graph.py"
        mod_path.write_text(code)
        m = importlib.util.module_from_spec(importlib.util.spec_from_file_location(mod_path.stem, mod_path))
        m.__spec__.loader.exec_module(m)  # type: ignore[union-attr]
        host = _Host()
        same = topology(m.build(host)) == topology(build_state_graph(spec, host))
        mermaid = build_state_graph(spec, host).compile().get_graph().draw_mermaid()
        (dst_p / f"{path.stem}.mmd").write_text(mermaid)
        print(f"{'OK ' if same else 'DIFF'} {path.name}: {len(spec.nodes)} nodes -> {mod_path.name}, {path.stem}.mmd")
        bad += 0 if same else 1
    return bad


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))

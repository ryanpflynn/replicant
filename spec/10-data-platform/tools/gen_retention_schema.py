#!/usr/bin/env python3
"""Generate schemas/policy-retention.schema.json from the C-ART artifact-type table (R1-238).

For each artifact type a tenant may choose its C-ART class or any SHORTER class that the type's
bucket accepts (tools/gen_s3_config.BUCKETS), so a schema-valid policy can never produce an upload
the bucket policy rejects. Excluded: session-state types (governed by sessionStateGraceDays),
`perm` types, registry/eval platform types, and audit types (Object Lock, platform policy), except
workflow_history_skeleton, which C-ART lets a tenant policy raise from r2y to r7y.
Usage: gen_retention_schema.py  (writes the schema and prints the per-type enums).
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from gen_s3_config import BUCKETS  # noqa: E402

ORDER = ["r7d", "r30d", "job37d", "r90d", "r1y", "r2y", "r7y"]
# Platform-controlled types a tenant may NOT shorten: idempotency and replay records (agentrun_record backs
# the 45-day 410 tombstone; manifests and indexes commit runs), audit evidence referenced by digest from
# Object-Locked records (approval_packet, approval_text), security evidence (secret_scan_report), and
# memory reproducibility (D-14/D-25: memory retention is admin policy, not tenant policy).
PLATFORM_CONTROLLED = {"agentrun_record", "run_manifest", "run_result", "job_artifact_index", "steering_control",
                       "approval_packet", "approval_text", "secret_scan_report", "memory_injection",
                       "context_assembly_report", "memory_snapshot_export", "memory_export", "memory_candidates",
                       "workflow_history_export"}
cart = (ROOT.parent / "00-contracts" / "artifact-layout.md").read_text()
types: dict[str, list[str]] = {}
for line in cart.splitlines():
    m = re.match(r"\| `([a-z_]+)` \| (artifacts|transcripts|session|audit|memory|eval|registry) \|", line)
    if not m:
        continue
    cols = [c.strip() for c in line.split("|")]
    t, bucket, ret = m.group(1), m.group(2), cols[5].split()[0]
    if bucket in ("session", "registry", "eval", "memory") or ret not in ORDER or t in PLATFORM_CONTROLLED:
        continue
    if bucket == "audit":
        if t == "workflow_history_skeleton":
            types[t] = ["r2y", "r7y"]
        continue
    allowed = [c for c in ORDER[: ORDER.index(ret) + 1] if c in BUCKETS[bucket]["classes"]]
    types[t] = allowed

schema = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "$id": "https://schemas.replicant.example.com/kinds/policy-retention/v1.json",
    "title": "Policy spec, policyType retention (owner WS-10)",
    "description": ("Behavioral retention choices carried in a Release Bundle (C-DEF §2). Per artifact type, the "
                    "allowed classes are its C-ART 1.9.0 class or a shorter class its bucket accepts (generated by "
                    "tools/gen_retention_schema.py, so no schema-valid policy can produce a rejected upload). "
                    "Tightening only (ADR-013), except workflow_history_skeleton r7y, which C-ART allows by policy."),
    "type": "object",
    "additionalProperties": False,
    "required": ["policyType"],
    "properties": {
        "policyType": {"const": "retention"},
        "artifactRetention": {
            "type": "object", "additionalProperties": False,
            "properties": {t: {"enum": v} for t, v in sorted(types.items())},
        },
        "sessionStateGraceDays": {
            "description": ("Days after the job's TERMINAL state before cli_session_state (and other run session objects) "
                            "is purged by the retention sweeper (C-ART job37d). workspace_archive is never swept: it keeps "
                            "its 30-day lifecycle retention (ruling on R1V-066). The 37-day lifecycle backstop still applies. "
                            "0..7; default 7. The sweeper reads it from the job's pinned bundle."),
            "type": "integer", "minimum": 0, "maximum": 7, "default": 7,
        },
        "screenshotsRequireMasking": {
            "description": "If true, producers refuse to upload screenshot artifacts without masking metadata (WS-05/WS-08).",
            "type": "boolean", "default": False,
        },
    },
}
(ROOT / "schemas" / "policy-retention.schema.json").write_text(json.dumps(schema, indent=2) + "\n")
for t, v in sorted(types.items()):
    print(f"{t}: {v}")
